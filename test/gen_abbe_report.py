                '2. 将一维光栅置于物面，白屏上得到清晰放大像；将白屏移至频谱面，观察到离散衍射斑。测各级衍射斑距0级距离x，计算空间频率ν=x/(λf)。\n'
                '3. 在频谱面依次放置不同光阑（仅0级、0级+±1级、全开、挡住±1级），观察并记录一维光栅像的变化。\n'
                '4. 换用正交光栅，观察二维频谱点阵；在频谱面放置可转动狭缝，分别让垂直、水平、45°方向频谱通过，记录像的变化。\n'
