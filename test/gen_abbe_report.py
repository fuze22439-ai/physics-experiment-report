"""生成阿贝成像实验报告 — 基于模板复制后精确填充"""
from docx import Document
from docx.shared import RGBColor

template = r'E:\物理实验报告II\实验报告模版.docx'
output = r'E:\物理实验报告II\test\阿贝成像_实验报告.docx'

doc = Document(template)

def find_para(doc, keyword):
    for p in doc.paragraphs:
        if keyword in p.text:
            return p
    return None

def set_text(para, text):
    """清除paragraph所有run后设置新文本，黑色字体，保留其他格式"""
    for run in para.runs:
        run.text = ''
    if para.runs:
        run = para.runs[0]
        run.text = text
        run.font.color.rgb = RGBColor(0, 0, 0)
    else:
        run = para.add_run(text)
        run.font.color.rgb = RGBColor(0, 0, 0)

print('填充模板...')

# 实验项目
p = find_para(doc, '实验项目：')
if p: set_text(p, '实验项目：阿贝成像与空间滤波')

